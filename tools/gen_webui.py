#!/usr/bin/env python3
"""Embed src/mg_webui/www/index.html into src/mg_webui/index_html.h.

Run after editing the page:  python3 tools/gen_webui.py
The generated header is committed, so the Momentics build needs no Python.
"""
import os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, "src", "mg_webui", "www", "index.html")
dst = os.path.join(root, "src", "mg_webui", "index_html.h")
data = open(src, "rb").read().decode("utf-8")
lines = ["/* GENERATED by tools/gen_webui.py from www/index.html - do not edit */",
         "#ifndef MG_INDEX_HTML_H", "#define MG_INDEX_HTML_H", "static const char MG_INDEX_HTML[] ="]
for line in data.splitlines(True):
    b = line.encode("utf-8")
    out = []
    for c in b:
        if c == 0x5C: out.append("\\\\")
        elif c == 0x22: out.append('\\"')
        elif c == 0x0A: out.append("\\n")
        elif c == 0x0D: continue
        elif c == 0x3F: out.append("\\?")          # no trigraphs
        elif 0x20 <= c < 0x7F: out.append(chr(c))
        else: out.append("\\%03o" % c)
    lines.append('    "' + "".join(out) + '"')
lines += ["    ;", "#endif", ""]
open(dst, "w", newline="\n").write("\n".join(lines))
print("wrote %s (%d bytes of HTML)" % (dst, len(data.encode("utf-8"))))
