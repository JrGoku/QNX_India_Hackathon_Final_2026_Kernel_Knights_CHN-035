def columns(rows):
    assert len(rows) == 7 and all(len(r) == 5 for r in rows), rows
    out = []
    for x in range(5):
        b = 0
        for y in range(7):
            if rows[y][x] == '#':
                b |= 1 << y
        out.append(b)
    return out


def main():
    root = Path(__file__).resolve().parent.parent
    lines = ["/* Generated by tools/gen_font.py - original 5x7 font, column-major, bit0 = top */",
             "#ifndef MG_FONT5X7_H", "#define MG_FONT5X7_H", "#include <stdint.h>",
             "static const uint8_t mg_font5x7[96][5] = {"]
    for code in range(32, 128):
        ch = chr(code)
        rows = G.get(ch) or G.get(ch.upper()) or G['?']
        cols = columns(rows)
        label = {'\\': 'backslash', '\x7f': 'block'}.get(ch, ch)
        lines.append("    { %s }, /* %s */" % (", ".join("0x%02X" % c for c in cols), label.replace('*/', '* /')))
    lines += ["};", "#endif", ""]
    out = root / "src" / "common" / "mg_font5x7.h"
    out.write_text("\n".join(lines))
    print("wrote", out)

    if len(sys.argv) > 1:
        from PIL import Image
        text = "0123456789 ABCDEFGHIJKLM NOPQRSTUVWXYZ !\"#%'()*+,-./:;<=>?[]_|\x7f"
        scale = 4
        img = Image.new("L", ((len(text) // 2 + 2) * 6 * scale, 20 * scale), 0)
        px = img.load()
        for i, ch in enumerate(text):
            row = 0 if i < len(text) // 2 else 1
            col = i if row == 0 else i - len(text) // 2
            cols = columns(G.get(ch, G['?']))
            for x, b in enumerate(cols):
                for y in range(7):
                    if b >> y & 1:
                        for dx in range(scale):
                            for dy in range(scale):
                                px[(col * 6 + x) * scale + dx, (row * 10 + y + 1) * scale + dy] = 255
        img.save(sys.argv[1])
        print("preview", sys.argv[1])


if __name__ == "__main__":
    main()
